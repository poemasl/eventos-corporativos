// ── Active language ──
let currentLang = 'es';

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  // Simple text keys
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // List keys
  document.querySelectorAll('[data-i18n-list]').forEach(ul => {
    const key = ul.getAttribute('data-i18n-list');
    if (Array.isArray(t[key])) {
      ul.innerHTML = t[key].map(item => `<li>${item}</li>`).join('');
    }
  });
}

// ── Language buttons ──
document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    currentLang = btn.getAttribute('data-lang');
    document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    document.documentElement.lang = currentLang;
    applyTranslations(currentLang);
  });
});

// ── Scroll reveal ──
const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      revealObserver.unobserve(entry.target);
    }
  });
}, {
  threshold: 0.12,
  rootMargin: '0px 0px -40px 0px'
});

document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

// ── Spotify play button ──
const heroPlay = document.getElementById('heroPlay');
const heroSpotify = document.getElementById('heroSpotify');
if (heroPlay && heroSpotify) {
  heroPlay.addEventListener('click', () => {
    if (heroSpotify.style.display === 'none') {
      heroSpotify.style.display = 'block';
      heroPlay.textContent = '⏸';
    } else {
      heroSpotify.style.display = 'none';
      heroPlay.textContent = '▶';
    }
  });
}

// ── Back to top ──
const backToTop = document.getElementById('backToTop');
window.addEventListener('scroll', () => {
  if (window.scrollY > 600) {
    backToTop.classList.add('visible');
  } else {
    backToTop.classList.remove('visible');
  }
});

// ── Init ──
const urlParams = new URLSearchParams(window.location.search);
const langParam = urlParams.get('lang');
if (langParam && translations[langParam]) {
  currentLang = langParam;
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === currentLang);
  });
  document.documentElement.lang = currentLang;
}
applyTranslations(currentLang);

